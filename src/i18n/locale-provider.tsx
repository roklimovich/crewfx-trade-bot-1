'use client';

import { createContext, useContext, useState, useCallback } from 'react';
import { useRouter } from 'next/navigation';
import { apiFetch } from '@/lib/api-client';
import { en } from './locales/en';
import { ru } from './locales/ru';
import { LOCALE_COOKIE, type Locale } from './config';
import type { Messages } from './locales/en';

const dictionaries: Record<Locale, Messages> = { en, ru };

interface LocaleContextValue {
  locale: Locale;
  messages: Messages;
  setLocale: (locale: Locale) => void;
}

const LocaleContext = createContext<LocaleContextValue | null>(null);

/**
 * Wraps the app once, in the root layout. `initialLocale` comes from the server (via the
 * NEXT_LOCALE cookie, read in the Server Component root layout) specifically so the very first
 * client render matches what the server already sent — no flash of the wrong language, no
 * hydration mismatch warning.
 */
export function LocaleProvider({
  initialLocale,
  children,
}: {
  initialLocale: Locale;
  children: React.ReactNode;
}) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale);
  const router = useRouter();

  const setLocale = useCallback(
    (next: Locale) => {
      document.cookie = `${LOCALE_COOKIE}=${next}; path=/; max-age=${60 * 60 * 24 * 365}; SameSite=Lax`;
      setLocaleState(next);

      // Best-effort persistence for logged-in users — notification content (Phase 10/13) is
      // generated by a background cron job with no request/cookie context of its own, so it
      // needs the choice saved on the User row, not just this browser's cookie. Silently
      // ignored if the request fails (e.g. not logged in yet, so CSRF/401 rejects it) — the
      // cookie-based experience on this device still works regardless.
      apiFetch('/api/auth/me', { method: 'PATCH', body: { locale: next } }).catch(() => {});

      // Server Components (pages, layouts) read the locale from the cookie independently —
      // refresh so they re-render in the new language too, not just this client subtree.
      router.refresh();
    },
    [router],
  );

  return (
    <LocaleContext.Provider value={{ locale, messages: dictionaries[locale], setLocale }}>
      {children}
    </LocaleContext.Provider>
  );
}

/** Client Component hook — returns the current locale, its full message dictionary, and a setter. */
export function useTranslations() {
  const ctx = useContext(LocaleContext);
  if (!ctx) throw new Error('useTranslations() must be used within <LocaleProvider>.');
  return ctx;
}
